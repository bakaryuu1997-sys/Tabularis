import { useMemo } from "react";
import { invoke } from "@tauri-apps/api/core";
import type { ExplainPlan, WhatIfExplainOutcome } from "../types/explain";
import {
  compareWhatIf,
  findIndexCandidates,
  type IndexCandidate,
  type WhatIfComparison,
} from "../utils/aiExplainDiff";
import { useKeyedAsync, type KeyedAsyncState } from "./useKeyedAsync";

export type WhatIfState =
  | { status: "no_connection" }
  | { status: "no_candidates" }
  | { status: "loading" }
  | { status: "unsupported" }
  | { status: "extension_missing"; extension: string }
  | { status: "error"; message: string }
  | { status: "ready"; afterPlan: ExplainPlan; comparison: WhatIfComparison };

export interface IndexAdvisor {
  candidates: IndexCandidate[];
  whatIf: WhatIfState;
  /** CREATE INDEX statements per candidate (same order as `candidates`), once generated. */
  ddl: KeyedAsyncState<string[][]>;
}

/**
 * Index advisor for a real EXPLAIN plan.
 *
 * Candidates come from the plan itself. Cost numbers come from the backend's
 * what-if EXPLAIN (the database planner), never from a local simulation. DDL is
 * generated by the driver so the frontend stays driver-agnostic.
 */
export function useIndexAdvisor(
  plan: ExplainPlan | null,
  connectionId: string | null | undefined,
  schema: string | null | undefined,
): IndexAdvisor {
  const candidates = useMemo(() => (plan ? findIndexCandidates(plan) : []), [plan]);
  const canQuery = !!plan && !!connectionId && candidates.length > 0;

  const key = useMemo(
    () =>
      JSON.stringify([
        connectionId,
        schema ?? null,
        plan?.original_query,
        candidates.map((c) => [c.tableName, c.columns]),
      ]),
    [connectionId, schema, plan, candidates],
  );

  const whatIfRaw = useKeyedAsync<WhatIfExplainOutcome>(key, canQuery, () =>
    invoke<WhatIfExplainOutcome>("explain_query_what_if", {
      connectionId,
      query: plan?.original_query ?? "",
      indexes: candidates.map((c) => ({ table: c.tableName, columns: c.columns })),
      schema: schema ?? null,
    }),
  );

  const ddl = useKeyedAsync<string[][]>(key, canQuery, () =>
    Promise.all(
      candidates.map((c) =>
        invoke<string[]>("get_create_index_sql", {
          connectionId,
          table: c.tableName,
          indexName: c.indexName,
          columns: c.columns,
          isUnique: false,
          ...(schema ? { schema } : {}),
        }),
      ),
    ),
  );

  const whatIf = useMemo<WhatIfState>(() => {
    if (!plan || candidates.length === 0) return { status: "no_candidates" };
    if (!connectionId) return { status: "no_connection" };
    if (whatIfRaw.status === "idle" || whatIfRaw.status === "loading") return { status: "loading" };
    if (whatIfRaw.status === "error") return { status: "error", message: whatIfRaw.message };
    const outcome = whatIfRaw.value;
    if (outcome.status === "plan") {
      return {
        status: "ready",
        afterPlan: outcome.plan,
        comparison: compareWhatIf(plan, outcome.plan, candidates),
      };
    }
    return outcome;
  }, [plan, candidates, connectionId, whatIfRaw]);

  return { candidates, whatIf, ddl };
}
